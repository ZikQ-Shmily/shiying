const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const nodes=new Map();
function node(key){if(!nodes.has(key))nodes.set(key,{innerHTML:'',textContent:'',value:'',dataset:{},style:{},open:true,disabled:false,classList:{add(){},remove(){}},addEventListener(){}});return nodes.get(key);}
const document={body:{dataset:{}},querySelector:node,querySelectorAll(){return[]},addEventListener(){}};
const c=vm.createContext({document,window:{addEventListener(){}},console,Date,Intl,URL,setTimeout(){},clearTimeout(){}});
vm.runInContext(fs.readFileSync(__dirname+'/../static/app.js','utf8'),c);
vm.runInContext(fs.readFileSync(__dirname+'/../static/integration.js','utf8'),c);
const run=code=>vm.runInContext(code,c);
const fields=new Map();
c.card={dataset:{sourceId:'source'},isConnected:true,querySelector:selector=>fields.get(selector)};
c.button={disabled:false,innerHTML:'',closest:()=>c.card};
for(const key of ['episodes','share_url','code']) fields.set('[name="'+key+'"]',{value:''});
fields.set('[name="movie_available"]',{checked:false});
fields.set('.source-scan-status',{textContent:''});
node('#item-form').querySelector=selector=>selector==='[name="kind"]'?{disabled:true}:{value:'1'};
function setup(value=''){
  run('state.role="admin";isAdministrator=()=>state.role==="admin";stamp=value=>value;state.editing={id:"work",season:1,sources:[{id:"source",share_url:"https://115.com/s/abc123",code:"abcd",episodes:""}]}');
  fields.get('[name="episodes"]').value=value;
  fields.get('[name="share_url"]').value='https://115.com/s/abc123';
  fields.get('[name="code"]').value='abcd';
  fields.get('.source-scan-status').textContent='';
  fields.get('[name="movie_available"]').checked=false;
}
const episodes=()=>fields.get('[name="episodes"]').value;
const status=()=>fields.get('.source-scan-status').textContent;
(async()=>{
  setup();
  run('var requests=0;api=async()=>{requests++;return {result:{state:"complete",episodes:"1-6",episode_count:6,checked_at:"10/25 02:00"}}}');
  await run('scanSourceEpisodes(button)');
  assert.equal(episodes(),'1-6');assert(status().includes('保存修改后生效'));assert.equal(c.button.disabled,false);
  setup('1-2');
  run('api=async()=>({result:{state:"partial",episodes:"1-3",episode_count:3,unrecognized_count:1,examples:["正片.mp4"]}})');
  await run('scanSourceEpisodes(button)');
  assert.equal(episodes(),'1-2');assert(status().includes('原值保留'));
  setup('1-2');run('api=async()=>{throw new Error("目录读取失败，原集数已保留")}');
  await run('scanSourceEpisodes(button)');assert.equal(episodes(),'1-2');assert(status().includes('失败'));
  setup();run('var resolveScan;api=()=>new Promise(resolve=>resolveScan=resolve)');
  let pending=run('scanSourceEpisodes(button)');
  fields.get('[name="episodes"]').value='1-4';
  run('resolveScan({result:{state:"complete",episodes:"1-6",episode_count:6}})');await pending;
  assert.equal(episodes(),'1-4');assert(status().includes('保留你的修改'));
  setup();pending=run('scanSourceEpisodes(button)');run('state.editing={id:"other"};resolveScan({result:{state:"complete",episodes:"1-6",episode_count:6}})');await pending;
  assert.equal(episodes(),'');
  setup();fields.get('[name="share_url"]').value='https://115.com/s/changed';
  run('api=()=>{throw new Error("must save first")}');await run('scanSourceEpisodes(button)');
  assert(status().includes('请先保存'));assert.equal(episodes(),'');
  run('var example={id:"work",title:"Test",kind:"tv",season:1,total_episodes:40,library_episodes:"1-5",library_count:5,aired_count:6,aired_episodes:"1-6",status:"missing",sources:[{id:"s",episodes:"1-6",episode_scan:{state:"complete",checked_at:"2026-10-25T04:00:00+08:00"}}],active_source_id:"s",tmdb:{id:1},emby:{state:"matched"}}');
  let html=run('embyComparison(example)');
  assert(html.indexOf('Emby 入库')<html.indexOf('TMDB 已播'));
  assert(html.includes('网盘当前来源')&&html.includes('1-6'));
  run('example.sources[0].episode_scan={state:"partial",message:"<script>unsafe</script>"}');
  html=run('sourceEpisodeProgress(example)');
  assert(html.includes('上次记录 6 集')&&html.includes('识别待核对')&&!html.includes('<script>'));
  run('example.sources[0].episodes="";example.sources[0].episode_scan=null');
  assert(run('sourceEpisodeProgress(example)').includes('待识别'));
  run('example.kind="movie"');
  assert(run('sourceEpisodeProgress(example)').includes('电影资源待检测'));
  assert(!run('sourceEpisodeMetric(example)').includes('待识别'));
  setup();run('state.editing.kind="movie";api=async()=>({result:{state:"complete",episodes:"1",episode_count:1,checked_at:"10/25 04:30"}})');
  await run('scanSourceEpisodes(button)');
  assert.equal(fields.get('[name="movie_available"]').checked,true);
  assert(status().includes('已检测到电影正片'));
  setup();run('state.editing.kind="movie";api=async()=>({result:{state:"empty",episodes:"",episode_count:0}})');
  await run('scanSourceEpisodes(button)');assert.equal(fields.get('[name="movie_available"]').checked,false);
  assert(status().includes('未检测到电影正片'));
  run('example.sources[0].episodes="1";example.sources[0].episode_scan={state:"complete"}');
  assert(run('sourceEpisodeProgress(example)').includes('网盘已有正片'));
  assert(!run('sourceEpisodeProgress(example)').includes(' · 1'));
  // The detail uses one comparison block and no duplicate actual-library summary.
  const detail=fs.readFileSync(__dirname+'/../static/integration.js','utf8').split('function openIntegratedDetail(id)')[1].split('document.addEventListener')[0];
  assert(!detail.includes('实际入库 / 手动记录')&&!detail.includes('detail-overview'));
  assert(fs.readFileSync(__dirname+'/../static/app.js','utf8').includes('<th>入库 / 已播进度</th>'));
  console.log('Verified source scans fill only complete results, preserve uncertain/failed/edited values, ignore stale responses and require saved links.');
})().catch(error=>{console.error(error);process.exitCode=1});
